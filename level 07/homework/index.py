# 3) კომენტარების სახით ახსენით რა არის logical operators, ჩამოწერეთ თითოეული და განმარტეთ რომელი რა დროს რა შედეგს გვიბრუნებს[cite: 1].
# Logical operators გამოიყენება პირობების გასაერთიანებლად და აბრუნებს True-ს ან False-ს.
# and - აბრუნებს True-ს მხოლოდ მაშინ, როცა ორივე პირობა True-ა, სხვა შემთხვევაში False-ს.
# or - აბრუნებს True-ს მაშინ, როცა ერთ-ერთი პირობა მაინც არის True, ხოლო False-ს როცა ორივე False-ია.
# not - აბრუნებს შებრუნებულ შედეგს (True-ს აქცევს False-ად, False-ს True-ად).


